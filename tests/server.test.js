const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { createApp } = require("../scripts/dev-server");
const { hash } = require("../scripts/content");
const { parseSource } = require('../scripts/templates');
const { projectRoot } = require("./helpers");
test("真实 HTTP 保存：版本、备份、并发冲突、校验和索引更新", async t => {
  const fixture = fs.mkdtempSync(path.join(os.tmpdir(), "interview-save-test-"));
  fs.cpSync(path.join(projectRoot, 'src'), path.join(fixture, 'src'), { recursive: true });
  const server = createApp(fixture).listen(0, "127.0.0.1");
  await new Promise(resolve => server.on("listening", resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); fs.rmSync(fixture, { recursive: true, force: true }); });
  const base = "http://127.0.0.1:" + server.address().port;
  const filePath = path.join(fixture, "src/developer/java.md"); const original = fs.readFileSync(filePath, "utf8");
  const page = await (await fetch(base + "/developer/java.html")).text();
  assert(page.includes('name="document-version" content="' + hash(original) + '"'));
  const body = { file: "java.html", version: hash(original), markdown: '## 保存校验题 {#save-test}\n\n### 面试快答\n\n新内容\n\n### 详细解析\n\n~~~java\nexact code {{ user }} {% if x %} {% endraw %}\n~~~' };
  const post = (data, extra = {}) => fetch(base + "/api/save", { method: "POST", headers: { "Content-Type": "application/json", ...extra }, body: JSON.stringify(data) });
  assert.equal((await post({ ...body, file: "../index.html" })).status, 400);
  assert.equal((await post({ ...body, version: null })).status, 428);
  assert.equal((await fetch(base + "/api/save", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{invalid" })).status, 400);
  assert.equal((await post({ ...body, markdown: "x".repeat(6 * 1024 * 1024) })).status, 413);
  assert.equal((await post(body, { Origin: "https://example.com" })).status, 403);
  assert.equal((await post({ ...body, markdown: '## 缺少固定ID\n\n无效内容' })).status, 400);
  assert.equal(fs.readFileSync(filePath, "utf8"), original);
  const saved = await post(body); assert.equal(saved.status, 200); const result = await saved.json();
  const updated = fs.readFileSync(filePath, "utf8"); assert.equal(result.version, hash(updated));
  assert.equal(parseSource(updated).prefix, parseSource(original).prefix, '保存不应改动页面元数据');
  const generated = fs.readFileSync(path.join(fixture, '_site/developer/java.html'), 'utf8');
  assert(generated.includes('exact code {{ user }} {% if x %} {% endraw %}'));
  assert(generated.includes('id="topicSelect"'));
  assert.equal(fs.readFileSync(path.join(fixture, ".local-backups/java.html.bak"), "utf8"), original);
  assert.equal((await post({ ...body, markdown: body.markdown.replace("新内容", "过期写入") })).status, 409);
  assert.equal(fs.readFileSync(filePath, "utf8"), updated);
  const index = JSON.parse(fs.readFileSync(path.join(fixture, "_site/assets/questions-index.json")));
  assert(index.questions.some(q => q.id === "save-test")); assert(!index.questions.some(q => q.category === "java" && q.id === "volatile"));
  assert.equal((await fetch(base + "/scripts/dev-server.js")).status, 404);
  assert.equal((await fetch(base + "/.local-backups/java.html.bak")).status, 404);
  assert.equal((await fetch(base + "/package.json")).status, 404);
  assert.equal((await fetch(base + '/src/developer/java.html')).status, 404);
  assert.equal((await fetch(base + '/eleventy.config.cjs')).status, 404);
  assert.equal((await post({ ...body, version: result.version, markdown: body.markdown.replace("新内容", "再次保存") })).status, 200);
  const current = fs.readFileSync(filePath, 'utf8');
  const brokenLayout = path.join(fixture, 'src/_includes/layouts/topic.njk');
  fs.writeFileSync(brokenLayout, '{% invalid-template %}');
  assert.equal((await post({ ...body, version: hash(current) })).status, 500);
  assert.equal(fs.readFileSync(filePath, 'utf8'), current, '模板损坏时不得覆盖正文');
  assert(!fs.readdirSync(path.dirname(filePath)).some(f => f.endsWith(".tmp")));
});
